/** Langue du téléphone, sans dépendance native : Intl est fourni par le moteur JS. */
export function deviceLang(): Lang {
  try {
    const loc = Intl.DateTimeFormat().resolvedOptions().locale ?? 'fr';
    return loc.toLowerCase().startsWith('fr') ? 'fr' : loc.toLowerCase().startsWith('en') ? 'en' : 'fr';
  } catch {
    return 'fr';
  }
}

export function t(key: Key, vars?: Record<string, string | number | undefined>): string {
  let s = dicts[current][key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v ?? ''));
  return s;
}

/** Choisit la forme au pluriel quand n > 1. */
export const tn = (one: Key, many: Key, n: number, vars?: Record<string, string | number | undefined>) =>
  t(n > 1 ? many : one, { n, ...vars });

/** « 1 minute », « 5 minutes » (même mot en français et en anglais). */
export const minutesWord = (n: number) => (n > 1 ? `${n} minutes` : `${n} minute`);

/** Le mot « Sortie » des données IDFM, dans la langue de l'appli. */
export const localExit = (s: string) => s.replace(/^(Sortie|Exit)/i, t('arr.exitGeneric'));

/** Une indication de sortie (« Sortie 3, Grande Arche » ou « Exit 3, … »). */
export const isExitTip = (s: string) => /^(Sortie|Exit)\b/i.test(s);
